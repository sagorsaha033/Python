# Convert string to integer
num_str = "33"
num_int = int(num_str)
print(num_int)
print(type(num_int))

# Convert integer to string
num = 100
num_str = str(num)
print(num_str)
print(type(num_str))

# Convert float to integer
pi = 77.77
pi_int = int(pi)
print(pi_int)
print(type(pi_int))
